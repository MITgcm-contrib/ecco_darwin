def read_native_normal_velocity(config_dir, bnd, itrs, bnd_domain, Nr0, verbose=False,
                                 legacy_bug_mode=False):
    """
    Reads the parent's native (diagnostics_vec) UVEL/VVEL at this boundary's
    native points, rotates into true zonal/meridional components (same
    convention gen_obcs.py/gen_obcs2.py use), and returns just the component
    normal to this boundary: zonal for east/west, meridional for north/south.

    Default behavior (matches a FIXED generator, e.g. gen_obcs2.py): every
    available "{bnd}_BC_mask_{vnm}.*" file is read and correctly
    concatenated in chronological (ascending iteration) order.

    Two ways to override:
      - if `itrs` names more than one iteration, it's treated as an
        explicit, authoritative list: exactly those files are read and
        correctly concatenated;
      - pass legacy_bug_mode=True to instead REPLICATE a known bug in the
        original, unfixed gen_obcs.py's read_dv_diags(): it globs every
        file present but a bug in its merge loop means only the FIRST and
        LAST file found (by raw glob order, not chronological) survive --
        everything in between is silently dropped. Use this only when
        checking an OBCS file you know was produced by the original
        gen_obcs.py, so this function's output matches what's actually
        baked into that file.

    Returns: (tstp, Nr0, n0) ndarray.
    """
    dv_dir = os.path.join(config_dir, 'parent/outputs/OBCS/')
    nm_pt = len(bnd_domain[bnd]['XC'])

    def _read_one(itr):
        U = np.fromfile(os.path.join(dv_dir, f"{bnd}_BC_mask_UVEL.{itr:010d}.bin"), '>f4')
        V = np.fromfile(os.path.join(dv_dir, f"{bnd}_BC_mask_VVEL.{itr:010d}.bin"), '>f4')
        tstp_i = U.size // (Nr0 * nm_pt)
        return U.reshape(tstp_i, Nr0, nm_pt), V.reshape(tstp_i, Nr0, nm_pt)

    if len(itrs) > 1:
        if verbose:
            print(f"    [{bnd}] explicit -i list given ({len(itrs)} iteration(s)); reading "
                  f"exactly those files, correctly concatenated")
        U_chunks, V_chunks = [], []
        for itr in sorted(itrs):
            U_i, V_i = _read_one(itr)
            if verbose:
                print(f"        - iteration {itr:010d}: {U_i.shape[0]} timestep(s)")
            U_chunks.append(U_i)
            V_chunks.append(V_i)
        dv_U = np.concatenate(U_chunks, axis=0)
        dv_V = np.concatenate(V_chunks, axis=0)
    elif legacy_bug_mode:
        sfx = os.path.join(dv_dir, "{bnd}_BC_mask_UVEL".format(bnd=bnd))
        found_itrs = [int(p[len(sfx) + 1:-4]) for p in glob.glob(sfx + ".*")]
        if not found_itrs:
            raise SystemExit(f"No {sfx}.*.bin files found -- has diagnostics_vec been run for "
                              f"the '{bnd}' boundary?")
        if verbose:
            print(f"    [{bnd}] --legacy-bug-mode: found {len(found_itrs)} native UVEL/VVEL "
                  f"file(s) (glob order, same as the original gen_obcs.py's read_dv_diags() "
                  f"would see):")

        dv_U_all = dv_V_all = dv_U = dv_V = None
        for i, itr in enumerate(found_itrs):
            U_i, V_i = _read_one(itr)
            if verbose:
                print(f"        - file {i}: iteration {itr:010d}, {U_i.shape[0]} timestep(s)")
            if i == 0:
                dv_U_all, dv_V_all = U_i, V_i
                dv_U, dv_V = U_i, V_i
            else:
                # exact replica of the original gen_obcs.py bug: concatenates
                # [FIRST file] with [this file], never the true running total
                dv_U = np.concatenate([dv_U_all, U_i], axis=0)
                dv_V = np.concatenate([dv_V_all, V_i], axis=0)
        if verbose:
            note = (" (matches file 0 exactly, only one file found)" if len(found_itrs) == 1 else
                    "" if len(found_itrs) == 2 else
                    f" -- files 1..{len(found_itrs)-2} were read then silently discarded by the "
                    f"replicated legacy bug")
            print(f"    [{bnd}] final native array: {dv_U.shape[0]} timestep(s) total{note}")
    else:
        sfx = os.path.join(dv_dir, f"{bnd}_BC_mask_UVEL")
        found_itrs = sorted(int(p[len(sfx) + 1:-4]) for p in glob.glob(sfx + ".*"))
        if not found_itrs:
            raise SystemExit(f"No {sfx}.*.bin files found -- has diagnostics_vec been run for "
                              f"the '{bnd}' boundary?")
        if verbose:
            print(f"    [{bnd}] found {len(found_itrs)} native UVEL/VVEL file(s); reading all, "
                  f"sorted chronologically ascending:")
        U_chunks, V_chunks = [], []
        for itr in found_itrs:
            U_i, V_i = _read_one(itr)
            if verbose:
                print(f"        - iteration {itr:010d}: {U_i.shape[0]} timestep(s)")
            U_chunks.append(U_i)
            V_chunks.append(V_i)
        dv_U = np.concatenate(U_chunks, axis=0)
        dv_V = np.concatenate(V_chunks, axis=0)
        if verbose:
            print(f"    [{bnd}] final native array: {dv_U.shape[0]} timestep(s) total (all "
                  f"{len(found_itrs)} file(s))")

    AngleCS = bnd_domain[bnd]['AngleCS']
    AngleSN = bnd_domain[bnd]['AngleSN']
    if bnd in ('east', 'west'):
        return AngleCS[None, None, :] * dv_U - AngleSN[None, None, :] * dv_V
    else:
        return AngleSN[None, None, :] * dv_U + AngleCS[None, None, :] * dv_V


def read_child_velocity(obcs_dir, bnd, vnm, Nr1, n1):
    """Reads an OBCS binary file gen_obcs.py already wrote. Returns (tstp, Nr1, n1)."""
    path = os.path.join(obcs_dir, f"{vnm}_{bnd}.bin")
    data = np.fromfile(path, '>f4')
    tstp = data.size // (Nr1 * n1)
    return data.reshape(tstp, Nr1, n1)

