def main(config_dir, reg_nm, boundaries, itrs, do_correct, do_plot, output_dir,
         max_correction_speed, velocity_tolerance, verbose, legacy_bug_mode=False):
    grd_ls = ['XC', 'YC', 'AngleCS', 'AngleSN', 'HFacC', 'HFacS', 'HFacW', 'drF']
    obcs_dir = os.path.join(config_dir, 'forcings/OBCS/')

    if verbose:
        print('> Reading parent and downscaled grid geometry')
    tmp = read_eccogrid(config_dir, reg_nm)
    grid0 = dict(zip(grd_ls + ['rF'], tmp))
    Nr0 = tmp[grd_ls.index("HFacC")].shape[0]
    llc = tmp[grd_ls.index("XC")].shape[1]

    tmp = read_ncgrid(config_dir, reg_nm, grd_ls)
    ### Interior-face trim -- must stay identical to gen_obcs.py's, see the
    ### long comment there: [0] -> interior face of S/W, [-1] -> interior face
    ### of N/E, matching how MITgcm masks OBCS normal velocities.
    tmp[grd_ls.index("HFacS")] = tmp[grd_ls.index("HFacS")][:, 1:-1, :]
    tmp[grd_ls.index("HFacW")] = tmp[grd_ls.index("HFacW")][:, :, 1:-1]
    grid1 = dict(zip(grd_ls, tmp))
    Nr1 = tmp[grd_ls.index("HFacC")].shape[0]
    for nm in ['S', 'W']:
        m = np.copy(grid1["HFac" + nm]); m[m > 0] = 1
        grid1["mask" + nm] = m

    ### face lengths, needed on both the parent and downscaled side to turn
    ### velocity into transport; not part of gen_obcs.py's own grd_ls, but
    ### already present in the same source files it reads
    parent_grid_dir = os.path.join(config_dir, 'parent/outputs/grid/')
    grid0['dxG'] = transp_tiles(mds.rdmds(parent_grid_dir + 'DXG'))
    grid0['dyG'] = transp_tiles(mds.rdmds(parent_grid_dir + 'DYG'))
    tmp = read_ncgrid(config_dir, reg_nm, ['dxG', 'dyG'])
    ### dxG is (ny+1, nx) and dyG is (ny, nx+1): they live on the SAME
    ### staggered faces as HFacS/HFacW respectively, so they must get the SAME
    ### interior-face trim. Trimming them the other way round (dxG[:-1], as
    ### before) paired the interior-face mask with the outer-edge face length,
    ### so the transport integral mixed two different faces.
    grid1['dxG'] = tmp[0][1:-1, :]
    grid1['dyG'] = tmp[1][:, 1:-1]

    bnd_ls, dv_masks_ls = read_dv_masks(config_dir, boundaries, llc)
    bnd_domain = gen_bnd_domain(bnd_ls, dv_masks_ls, grid0, Nr0)
    ### gen_bnd_domain() only fills XC/YC/AngleCS/AngleSN/mask{C,S,W} for
    ### each boundary's native points; add dxG/dyG at those same points the
    ### same way, without touching gen_obcs.py itself
    _add_face_lengths_to_bnd_domain(bnd_domain, dv_masks_ls, bnd_ls, grid0)

    if do_correct:
        os.makedirs(output_dir, exist_ok=True)

    for bnd in bnd_ls:
        vnm = NORMAL_VNM[bnd]
        if bnd in ('east', 'west'):
            XC1 = grid1['XC'][:, -1:] if bnd == 'east' else grid1['XC'][:, :1]
            YC1 = grid1['YC'][:, -1:] if bnd == 'east' else grid1['YC'][:, :1]
            mask1 = grid1['maskW'][:, :, -1:] if bnd == 'east' else grid1['maskW'][:, :, :1]
            face1 = (grid1['dyG'][:, -1:] if bnd == 'east' else grid1['dyG'][:, :1]).ravel()
            coord1 = YC1.ravel()
        else:
            XC1 = grid1['XC'][-1:, :] if bnd == 'north' else grid1['XC'][:1, :]
            YC1 = grid1['YC'][-1:, :] if bnd == 'north' else grid1['YC'][:1, :]
            mask1 = grid1['maskS'][:, -1:, :] if bnd == 'north' else grid1['maskS'][:, :1, :]
            face1 = (grid1['dxG'][-1:, :] if bnd == 'north' else grid1['dxG'][:1, :]).ravel()
            coord1 = XC1.ravel()
        mask1_2d = mask1[:, :, 0] if bnd in ('east', 'west') else mask1[:, 0, :]
        n1 = mask1_2d.shape[1]

        if verbose:
            print(f'> [{bnd}] reading native parent velocity and downscaled {vnm}')
        native_vel = read_native_normal_velocity(config_dir, bnd, itrs, bnd_domain, Nr0, verbose=verbose,
                                                  legacy_bug_mode=legacy_bug_mode)
        child_vel = read_child_velocity(obcs_dir, bnd, vnm, Nr1, n1)
        print(f'    [{bnd}] {os.path.join(obcs_dir, f"{vnm}_{bnd}.bin")}: {child_vel.shape[0]} timestep(s)')
        if native_vel.shape[0] != child_vel.shape[0]:
            raise SystemExit(
                f"[{bnd}] timestep mismatch even after replicating gen_obcs.py's own file "
                f"discovery: native data has {native_vel.shape[0]} timestep(s), but "
                f"{os.path.join(obcs_dir, f'{vnm}_{bnd}.bin')} has {child_vel.shape[0]}. The "
                f"directory contents may have changed since gen_obcs.py was run (files added/"
                f"removed), which changes glob order. Pass the exact iteration(s) that were used "
                f"with multiple -i values to bypass auto-discovery entirely.")

        result = correct_boundary(bnd, bnd_domain, grid0, native_vel, coord1, face1,
                                   child_vel, mask1_2d, grid1['drF'],
                                   max_correction_speed=max_correction_speed,
                                   velocity_tolerance=velocity_tolerance)
        print_report(bnd, vnm, result)

        if do_plot:
            fpath = plot_boundary(bnd, vnm, reg_nm, result, os.path.join(output_dir or obcs_dir, 'diagnostics'))
            if verbose:
                print(f'    saved plot: {fpath}')

        if do_correct:
            out_path = os.path.join(output_dir, f'{vnm}_{bnd}.bin')
            result['corrected'].ravel('C').astype('>f4').tofile(out_path)
            if verbose:
                print(f'    wrote corrected file: {out_path}')

    if do_correct:
        ### copy every other boundary file (T/S/tracers/sea-ice/tangential
        ### velocity) through unchanged, so output_dir is a complete,
        ### ready-to-use set
        corrected_names = {f'{NORMAL_VNM[b]}_{b}.bin' for b in bnd_ls}
        for src in glob.glob(os.path.join(obcs_dir, '*.bin')):
            if os.path.basename(src) not in corrected_names:
                shutil.copy2(src, os.path.join(output_dir, os.path.basename(src)))
        if verbose:
            print(f'> copied remaining OBCS files (T/S/tracers/etc.) unchanged into {output_dir}')

