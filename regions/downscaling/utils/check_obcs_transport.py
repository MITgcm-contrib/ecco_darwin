def boundary_transport(vel, mask, drF, face):
    """
    Per-column transport (m^3/s) through a boundary.
        vel:  (..., Nr, n) velocity, normal to the boundary
        mask: (Nr, n) wet fraction (0/1 or hFac)
        drF:  (Nr,) vertical grid spacing
        face: (n,) along-boundary face length (dyG for east/west, dxG for
              north/south)
    Returns an array with the same leading shape as vel, minus the Nr axis.
    """
    return face * np.sum(vel * mask * drF[:, None], axis=-2)


def correct_boundary(bnd, bnd_domain, grid0, native_vel, coord1, face1,
                      child_vel, mask1, drF1, max_correction_speed=2.0,
                      velocity_tolerance=0.2):
    """
    Per-boundary barotropic correction: a SINGLE depth- and space-uniform
    velocity offset, added everywhere this boundary is wet, so the
    boundary's TOTAL transport matches the parent's. Both the baroclinic
    (depth-varying) shape and the along-boundary spatial pattern gen_obcs.py
    already produced are left completely untouched -- only one number per
    timestep is added on top of the existing field.

    The correction is capped two ways, whichever is more restrictive:
      - an absolute cap, +/-max_correction_speed (m/s);
      - a cap derived from the parent's own velocity range at this
        boundary: the correction won't push the field's own min/max beyond
        [parent_min, parent_max] by more than velocity_tolerance (a
        fraction of the parent's speed range, default 0.2 = 20%).

    native_vel: (tstp, Nr0, n0) parent normal velocity, from
        read_native_normal_velocity().
    child_vel: (tstp, Nr1, n1) downscaled normal velocity, from
        read_child_velocity().

    Returns a dict with everything needed to report on / plot the result.
    """
    if bnd in ('east', 'west'):
        coord0 = bnd_domain[bnd]['YC']
        face0 = bnd_domain[bnd]['dyG']
        hFac0 = bnd_domain[bnd]['maskW']
    else:
        coord0 = bnd_domain[bnd]['XC']
        face0 = bnd_domain[bnd]['dxG']
        hFac0 = bnd_domain[bnd]['maskS']
    drF0 = grid0['drF']

    ### Parent (native) transport, summed over the whole boundary, per timestep
    Tp_col = boundary_transport(native_vel, hFac0, drF0, face0)         # (tstp, n0)
    Tp_total = Tp_col.sum(axis=1)                                       # (tstp,)

    ### Downscaled (child) transport before correction, summed over the
    ### whole boundary
    Tc_col_before = boundary_transport(child_vel, mask1, drF1, face1)   # (tstp, n1)
    Tc_total_before = Tc_col_before.sum(axis=1)                         # (tstp,)

    ### Single barotropic correction velocity for the whole boundary
    wet = mask1 > 0
    A_total = float(np.sum(face1 * np.sum(wet * drF1[:, None], axis=0)))   # total wet cross-section, m^2
    dU_raw = np.divide(Tp_total - Tc_total_before, A_total,
                        out=np.zeros_like(Tp_total), where=A_total > 0)    # (tstp,)

    ### Cap 1: absolute limit on the correction itself
    lo_abs, hi_abs = -max_correction_speed, max_correction_speed

    ### Cap 2: don't let the correction push the field's own min/max beyond
    ### the parent's observed range (+/- a tolerance margin)
    parent_min = float(native_vel.min())
    parent_max = float(native_vel.max())
    margin = velocity_tolerance * max(abs(parent_min), abs(parent_max), 0.01)
    range_lo, range_hi = parent_min - margin, parent_max + margin
    child_masked = np.where(wet[None, :, :], child_vel, np.nan)
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', category=RuntimeWarning)   # no wet cells at all -> handled below
        global_min_before = np.nanmin(child_masked, axis=(1, 2))    # (tstp,)
        global_max_before = np.nanmax(child_masked, axis=(1, 2))
    lo_range = range_lo - global_min_before
    hi_range = range_hi - global_max_before
    lo_range = np.where(np.isnan(lo_range), lo_abs, lo_range)
    hi_range = np.where(np.isnan(hi_range), hi_abs, hi_range)

    dU_lo = np.maximum(lo_abs, lo_range)
    dU_hi = np.minimum(hi_abs, hi_range)
    dU_lo = np.minimum(dU_lo, dU_hi)   # guard against the pre-existing (uncorrected)
                                        # field already sitting outside the tolerated
                                        # range -- clip() needs lo<=hi
    dU = np.clip(dU_raw, dU_lo, dU_hi)                                  # (tstp,)

    corrected = child_vel + dU[:, None, None] * wet[None, :, :]
    Tc_col_after = boundary_transport(corrected, mask1, drF1, face1)    # (tstp, n1)
    Tc_total_after = Tc_col_after.sum(axis=1)                           # (tstp,)

    was_clipped = np.abs(dU - dU_raw) > 1e-9
    clipped_frac = float(np.mean(was_clipped))
    wet_len_frac = float(np.sum(face1[np.sum(wet, axis=0) > 0]) / np.sum(face1)) if np.sum(face1) > 0 else 0.0

    corrected_masked = np.where(wet[None, :, :], corrected, np.nan)

    return {
        'corrected': corrected,
        'coord0': coord0, 'coord1': coord1, 'face1': face1,
        'Tp_total': Tp_total, 'Tc_total_before': Tc_total_before, 'Tc_total_after': Tc_total_after,
        'dU': dU, 'dU_raw': dU_raw, 'wet_len_frac': wet_len_frac, 'clipped_frac': clipped_frac,
        'parent_min': parent_min, 'parent_max': parent_max,
        'tolerated_min': range_lo, 'tolerated_max': range_hi,
        'child_min_before': float(np.nanmin(child_masked)) if np.any(wet) else 0.0,
        'child_max_before': float(np.nanmax(child_masked)) if np.any(wet) else 0.0,
        'child_min_after': float(np.nanmin(corrected_masked)) if np.any(wet) else 0.0,
        'child_max_after': float(np.nanmax(corrected_masked)) if np.any(wet) else 0.0,
        # kept for the transect plot: the per-column pattern is unchanged by
        # a bulk correction, so "before" and "after" transects only differ
        # by the constant dU (broadcast, no extra computation needed)
        'q0_col': np.divide(Tp_col, face0, out=np.zeros_like(Tp_col), where=face0 > 0),
        'Tc_col_before': Tc_col_before, 'Tc_col_after': Tc_col_after,
    }

