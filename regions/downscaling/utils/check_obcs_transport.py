"""
check_obcs_transport.py

Post-hoc check (and optional correction) of the volume transport carried by
the boundary-normal velocity OBCs that gen_obcs.py already generated,
against the transport actually simulated by the parent (LLC270) model at
the same boundary.

This is intentionally a separate script from gen_obcs.py: it only READS the
OBCS binary files gen_obcs.py already wrote to <config_dir>/forcings/OBCS/,
and it does not modify gen_obcs.py at all -- it just imports a few of its
existing, unmodified grid-reading helpers.

NOTE on a known bug in the ORIGINAL gen_obcs.py (fixed in gen_obcs2.py):
its read_dv_diags() takes an -i iteration list but never actually uses it
to select native diagnostics_vec files -- it globs and reads EVERY
"{bnd}_BC_mask_{vnm}.*" file present in parent/outputs/OBCS/, then a bug in
its merge loop means only the FIRST and LAST file found (by glob order)
survive; anything in between is silently dropped. By default,
read_native_normal_velocity() below reads and correctly concatenates every
available file (matching a fixed generator like gen_obcs2.py). Pass
-legacy-bug-mode to instead replicate the original bug, if you're checking
an OBCS file you know was generated by the unfixed gen_obcs.py.

Workflow:
    1. Run gen_obcs.py as usual to generate forcings/OBCS/*.bin.
    2. Run this script to see the parent-vs-downscaled transport mismatch
       for each open boundary (and optionally a diagnostic plot).
    3. If you want it corrected, pass -correct: a single, per-boundary
       barotropic velocity offset (uniform across depth AND along the whole
       boundary, so both the baroclinic shape and the along-boundary
       spatial pattern gen_obcs.py already produced are left untouched) is
       added to UVEL/VVEL so the boundary's total transport matches the
       parent's, and written to a *separate* output directory (default
       forcings/OBCS_corrected/) alongside untouched copies of the other
       boundary files, so you can point data.obcs at whichever set you
       trust.

Example:
    python3 check_obcs_transport.py -d /path/to/grid -n GoM_1km -bnd ENS \\
                                     -i 26281 -correct -plot -v
"""
