def plot_boundary(bnd, vnm, reg_nm, result, plot_dir):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    coord0, coord1, face1 = result['coord0'], result['coord1'], result['face1']
    q0 = result['q0_col']
    q_before = np.divide(result['Tc_col_before'], face1, out=np.zeros_like(result['Tc_col_before']), where=face1 > 0)
    q_after = np.divide(result['Tc_col_after'], face1, out=np.zeros_like(result['Tc_col_after']), where=face1 > 0)
    order0, order1 = np.argsort(coord0), np.argsort(coord1)
    sv_per_100km = 1e5 / 1e6

    fig, (ax0, ax1) = plt.subplots(1, 2, figsize=(13, 4.5))

    ax0.plot(coord0[order0], q0.mean(axis=0)[order0] * sv_per_100km, 'o-', ms=3, color='k',
             label='parent (native)')
    ax0.plot(coord1[order1], q_before.mean(axis=0)[order1] * sv_per_100km, '--', color='tab:orange',
             label='downscaled (before)')
    ax0.plot(coord1[order1], q_after.mean(axis=0)[order1] * sv_per_100km, '-', color='tab:green',
             label='downscaled (after = before + uniform shift)')
    ax0.axhline(0, color='gray', lw=0.5)
    ax0.set_xlabel('Latitude' if bnd in ('east', 'west') else 'Longitude')
    ax0.set_ylabel('Transport per unit length (Sv / 100 km)')
    ax0.set_title(f'{reg_nm} {bnd} boundary {vnm}\ntime-mean transect ({q0.shape[0]} step(s))')
    ax0.legend(fontsize=8)

    t_idx = np.arange(result['Tp_total'].shape[0])
    ax1.plot(t_idx, result['Tp_total'] / 1e6, '-', color='k', label='parent')
    ax1.plot(t_idx, result['Tc_total_before'] / 1e6, '--', color='tab:orange', label='downscaled (before)')
    ax1.plot(t_idx, result['Tc_total_after'] / 1e6, '-', color='tab:green', label='downscaled (after)')
    ax1.axhline(0, color='gray', lw=0.5)
    ax1.set_xlabel('Time step')
    ax1.set_ylabel('Net transport (Sv)')
    ax1.set_title('Boundary-integrated transport time series')
    ax1.legend(fontsize=8)

    fig.tight_layout()
    os.makedirs(plot_dir, exist_ok=True)
    fpath = os.path.join(plot_dir, f'{reg_nm}_{bnd}_{vnm}_transport_check.png')
    fig.savefig(fpath, dpi=150)
    plt.close(fig)
    return fpath

