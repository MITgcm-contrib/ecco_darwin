def print_report(bnd, vnm, result):
    Tp_tot = result['Tp_total'] / 1e6            # Sv, per timestep
    Tcb_tot = result['Tc_total_before'] / 1e6
    Tca_tot = result['Tc_total_after'] / 1e6
    mismatch_before = np.abs(Tp_tot - Tcb_tot)
    mismatch_after = np.abs(Tp_tot - Tca_tot)
    rel_before = mismatch_before.mean() / max(np.abs(Tp_tot).mean(), 1e-6)
    dU_max = np.max(np.abs(result['dU']))

    coord0, coord1 = result['coord0'], result['coord1']
    outside = (coord1 < coord0.min()) | (coord1 > coord0.max())
    frac_outside = float(np.sum(result['face1'][outside]) / np.sum(result['face1']))

    print(f"[{bnd}] {vnm} transport (Sv, {len(Tp_tot)} step(s)):")
    print(f"    parent (native)     : {Tp_tot.mean():8.3f}")
    print(f"    downscaled, before  : {Tcb_tot.mean():8.3f}   (mismatch {mismatch_before.mean():.3f} Sv, "
          f"{rel_before*100:.1f}%)")
    print(f"    downscaled, after   : {Tca_tot.mean():8.3f}   (residual {mismatch_after.mean():.3f} Sv)")
    print(f"    wet length fraction : {result['wet_len_frac']*100:.0f}%   "
          f"barotropic correction: {dU_max*100:.1f} cm/s (uniform across the whole boundary)"
          + (f"   (capped on {result['clipped_frac']*100:.1f}% of timesteps)" if result['clipped_frac'] > 0 else ""))
    print(f"    velocity (m/s)      : parent [{result['parent_min']:.2f}, {result['parent_max']:.2f}]   "
          f"downscaled before [{result['child_min_before']:.2f}, {result['child_max_before']:.2f}]   "
          f"after [{result['child_min_after']:.2f}, {result['child_max_after']:.2f}]")
    # compare against the *tolerated* range (parent range +/- velocity_tolerance),
    # not the raw parent min/max -- the correction is allowed to use that margin,
    # so exceeding parent's raw range alone isn't a problem, only exceeding the
    # tolerated range is
    out_of_range = (result['child_max_after'] > result['tolerated_max'] + 1e-9 or
                     result['child_min_after'] < result['tolerated_min'] - 1e-9)
    if out_of_range:
        print(f"    note: downscaled velocity range after correction still falls outside the parent's "
              f"tolerated range [{result['tolerated_min']:.2f}, {result['tolerated_max']:.2f}] -- this "
              f"usually means the pre-correction (baroclinic) field was already out of range before any "
              f"correction was applied (see the coverage note below if present), since the correction "
              f"itself is capped to not make this worse")
    if frac_outside > 0.05:
        print(f"    note: native samples span [{coord0.min():.2f}, {coord0.max():.2f}], downscaled "
              f"boundary spans [{coord1.min():.2f}, {coord1.max():.2f}] -- {frac_outside*100:.0f}% of the "
              f"boundary length falls outside native coverage (those columns' target is extrapolated from "
              f"the nearest native sample, not independently sampled data; consider regenerating "
              f"'{bnd}_BC_mask.bin' against the current domain if this fraction is large)")

