def _add_face_lengths_to_bnd_domain(bnd_domain, dv_masks_ls, bnd_ls, grid0):
    """gen_bnd_domain() only fills XC/YC/AngleCS/AngleSN/mask{C,S,W} for
    each boundary's native points; add dxG/dyG at those same points the
    same way, without touching gen_obcs.py."""
    for bnd, mask in zip(bnd_ls, dv_masks_ls):
        rows, cols = np.where(mask != 0)
        npts = len(bnd_domain[bnd]['XC'])
        dxG_pts = np.zeros(npts)
        dyG_pts = np.zeros(npts)
        for row, col in zip(rows, cols):
            idx = int(mask[row, col]) - 1
            dxG_pts[idx] = grid0['dxG'][row, col]
            dyG_pts[idx] = grid0['dyG'][row, col]
        bnd_domain[bnd]['dxG'] = dxG_pts
        bnd_domain[bnd]['dyG'] = dyG_pts

