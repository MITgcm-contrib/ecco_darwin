#!/bin/bash
# Nares 2026-11-15: build_drag10 = build_swfix + code_drag10 (ice-ocean drag on the top-10-m mean ocean velocity, Dustin fix (a)). Ask before qsub.
# (origin 2026-10-24: build_capload = build/ + code_capload, SEAICE_CAP_ICELOAD, ice load capped at 6 m water)
# after run_arch_ICTs crashed in CALC_R_STAR (numerical heff pile). build/ untouched (SD2e4 runs on it). Ask Dustin before qsub.
# Nares regional_run build -- adapted from pan_AO/regional_run/job_build.sh
# (2026-10-07). Same optfile, modules and Makefile hand-patches as pan_AO
# (read the pan_AO script for why: -mcmodel=medium for the >2 GB statics,
# and stripping -axCORE-AVX2 so the binary runs on AMD nodes). Differences:
# own darwin3 tree (below), 192 ranks, shelfice + iceplume, SEAICE JFNK/TEM +
# side/bottom drag, ALLOW_ADDFLUID. Needs input/{data.exch2,data.obcs} and
# input_darwin/data.ptracers to exist (pre-flight reads them).
#
# Ask Dustin before qsub.
#
#PBS -l select=1:ncpus=16:model=sky_ele
#PBS -q normal
#PBS -l walltime=1:00:00
#PBS -N nares_bdrg
#PBS -W group_list=s1353
#PBS -e /nobackup/dcarrol2/downscaling/nares/regional_run/build_drag10_err.txt
#PBS -o /nobackup/dcarrol2/downscaling/nares/regional_run/build_drag10_out.txt

module purge
module load comp-intel/2023.2.1 mpi-hpe/mpt.2.30 hdf4/4.2.12 hdf5/1.8.18_mpt netcdf/4.4.1.1_mpt python3/3.9.12
module list

# Nares builds against its own darwin3 clone, branch `nares`:
#   ce5f626cf = pan_AO darwin3_ckpt69k @1925cd1e1 + pan_AO's SEAICE_SWFrac
#               backport (committed in west_AO/darwin3), WITHOUT the WestAO
#               pkg/wad port;
#   8eb545d38 = + pkg/iceplume (nares_fixes c2e6dbd, see
#               model_setup/nares_strait/iceplume_pkg_fixes).
# The core files iceplume needs patched live in code/ (and apply_forcing.F
# in code_darwin/, which wins), written by the iceplume installer at 2cab8d1.
DARWIN3=/nobackup/dcarrol2/downscaling/nares/darwin3
P=/nobackup/dcarrol2/downscaling/nares/regional_run

# Full wipe, not a selective rm (from pan_AO 2026-09-30). genmake2 does NOT replace
# source/header symlinks that already exist, so a build dir that has seen a
# different package set or a different MITgcm tree ends up a mixture of both
# -- that is what produced `error #6404 [GSVEC_SIZE]` in gen_ncgrid earlier
# today (a fresh global_sum_vector.F linked against a stale EEPARAMS.h).
# This pass adds THREE packages (exch2, sun, oasim), which is exactly the
# situation where leftovers bite. Everything here is regenerated by genmake2.
cd "$P" || exit 1
rm -rf build_drag10
mkdir -p build_drag10
cd "$P/build_drag10" || exit 1

# --- pre-flight: Nares tree and packages ---
[ -d "$DARWIN3/pkg/iceplume" ] || { echo "FATAL: $DARWIN3/pkg/iceplume missing"; exit 1; }
git -C "$DARWIN3" log -1 --format="=== tree: %h %s ===" 2>/dev/null
for pk in shelfice iceplume obcs exch2 radtrans; do
  grep -qx "$pk" "$P/code_darwin/packages.conf" || { echo "FATAL: $pk not in packages.conf"; exit 1; }
done
grep -q "^#define ALLOW_ADDFLUID" "$P/code/CPP_OPTIONS.h" || { echo "FATAL: iceplume needs ALLOW_ADDFLUID"; exit 1; }
for f in SEAICE_ALLOW_JFNK SEAICE_ALLOW_TEM SEAICE_ALLOW_SIDEDRAG SEAICE_ALLOW_BOTTOMDRAG; do
  grep -qE "^# *define $f" "$P/code/SEAICE_OPTIONS.h" || { echo "FATAL: $f not defined"; exit 1; }
done

# Pre-flight: assert the tracer count the sources will compile matches the
# 33 that data.ptracers declares and that build_ptracer_map.py mapped.
# A silent 31/33 disagreement here is the whole reason that script exists.
PT_SRC=$(grep -oE 'PTRACERS_num *= *[0-9]+' "$P/code_darwin/PTRACERS_SIZE.h" | grep -oE '[0-9]+')
PT_NML=$(grep -oE 'PTRACERS_numInUse= *[0-9]+' "$P/input_darwin/data.ptracers" | grep -oE '[0-9]+')
echo "=== pre-flight: PTRACERS_SIZE.h=$PT_SRC  data.ptracers numInUse=$PT_NML ==="
if [ "$PT_SRC" != "33" ] || [ "$PT_NML" != "33" ]; then
  echo "FATAL: expected 33/33, got $PT_SRC/$PT_NML -- refusing to build."
  exit 1
fi

# Assert the rank count in SIZE.h matches what the production job will ask
# for, so a mismatch surfaces now and not as an MPI abort 5 hours into a
# queue wait.
# Nares: exch2 single facet 1120x360, 40x40 tiles: 252 - 60 blank = 192 active.
NPX=$(grep -oE 'nPx *= *[0-9]+' "$P/code/SIZE.h" | grep -oE '[0-9]+')
NPY=$(grep -oE 'nPy *= *[0-9]+' "$P/code/SIZE.h" | grep -oE '[0-9]+')
echo "=== pre-flight: nPx=$NPX nPy=$NPY -> $((NPX*NPY)) ranks ==="
if [ "$((NPX*NPY))" != "192" ]; then
  echo "FATAL: expected 192 active tiles, got $((NPX*NPY)) -- refusing to build."
  exit 1
fi

# The three numbers that must agree, checked against each other rather than
# against a hard-coded constant: total tiles implied by data.exch2's facet
# size and SIZE.h's tile size, minus the blankList length, must equal
# nPx*nPy. This is the consistency that silently breaks when any one of
# SIZE.h / data.exch2 / the blanklist is regenerated alone.
SNX=$(grep -oE 'sNx *= *[0-9]+' "$P/code/SIZE.h" | grep -oE '[0-9]+')
SNY=$(grep -oE 'sNy *= *[0-9]+' "$P/code/SIZE.h" | grep -oE '[0-9]+')
EX="$P/input/data.exch2"
[ -f "$EX" ] || { echo "FATAL: $EX missing -- exch2 is in packages.conf"; exit 1; }
FX=$(grep -oE 'dimsFacets *=[0-9, ]+' "$EX" | grep -oE '[0-9]+' | head -1)
FY=$(grep -oE 'dimsFacets *=[0-9, ]+' "$EX" | grep -oE '[0-9]+' | sed -n 2p)
NBLANK=$(sed -n '/blankList=/,$p' "$EX" | grep -oE '[0-9]+' | wc -l)
if [ $((FX % SNX)) -ne 0 ] || [ $((FY % SNY)) -ne 0 ]; then
  echo "FATAL: facet ${FX}x${FY} not divisible by tile ${SNX}x${SNY}"; exit 1
fi
NTOT=$(( (FX / SNX) * (FY / SNY) ))
echo "=== pre-flight: facet ${FX}x${FY}, tiles ${SNX}x${SNY} -> $NTOT total, $NBLANK blank, $((NTOT-NBLANK)) active ==="
if [ "$((NTOT - NBLANK))" != "$((NPX*NPY))" ]; then
  echo "FATAL: $NTOT total - $NBLANK blank = $((NTOT-NBLANK)) active, but SIZE.h says $((NPX*NPY))."
  exit 1
fi
NUNIQ=$(sed -n '/blankList=/,$p' "$EX" | grep -oE '[0-9]+' | sort -un | wc -l)
if [ "$NUNIQ" != "$NBLANK" ]; then
  echo "FATAL: blankList has duplicates ($NBLANK entries, $NUNIQ distinct)"; exit 1
fi

# --- pre-flight: namelist switches that need a CPP flag to do anything ----
# Added 2026-10-02. An OBCS runtime switch set .TRUE. while its CPP flag is
# #undef is READ AND SILENTLY IGNORED -- no error, no warning, and the
# namelist then documents a constraint the binary cannot apply. data.obcs
# already carried a hand-written warning about exactly this for
# useOBCSbalance; this makes it a check instead of a comment, because a
# comment only works on someone who reads it.
#
# Direction matters: "compiled in but switched off" is a VALID and intended
# state (the GMRedi/CTRL/SMOOTH/SALT_PLUME pattern -- build once, switch at
# runtime). Only .TRUE.-without-#define is an error, so this guard is
# deliberately one-directional and will not fire on a flag compiled in ahead
# of being used.
OBO="$P/code/OBCS_OPTIONS.h"
OBN="$P/input/data.obcs"
[ -f "$OBO" ] || { echo "FATAL: $OBO missing"; exit 1; }
[ -f "$OBN" ] || { echo "FATAL: $OBN missing"; exit 1; }
echo "=== pre-flight: OBCS namelist switches vs CPP flags ==="
OBCS_BAD=0
check_obcs_pair() {   # $1 = namelist var, $2 = CPP flag
  # active (non-commented) assignment set to .TRUE.
  if grep -qiE "^[[:space:]]*$1[[:space:]]*=[[:space:]]*\.TRUE\." "$OBN"; then
    if grep -qE "^#define[[:space:]]+$2([[:space:]]|$)" "$OBO"; then
      echo "    OK   $1=.TRUE.  and  #define $2"
    else
      echo "    FATAL  $1=.TRUE. in data.obcs but $2 is NOT defined in"
      echo "           code/OBCS_OPTIONS.h -- the switch would be silently ignored."
      OBCS_BAD=1
    fi
  else
    if grep -qE "^#define[[:space:]]+$2([[:space:]]|$)" "$OBO"; then
      echo "    ok   $1 off; $2 compiled in (available at runtime)"
    else
      echo "    ok   $1 off; $2 not compiled"
    fi
  fi
}
check_obcs_pair useOBCSbalance   ALLOW_OBCS_BALANCE
check_obcs_pair useOBCSsponge    ALLOW_OBCS_SPONGE
check_obcs_pair useSeaiceSponge  ALLOW_OBCS_SEAICE_SPONGE
check_obcs_pair useOBCSprescribe ALLOW_OBCS_PRESCRIBE
check_obcs_pair useOBCStides     ALLOW_OBCS_TIDES
[ "$OBCS_BAD" = "0" ] || { echo "FATAL: OBCS namelist/CPP mismatch -- refusing to build."; exit 1; }

# code_darwin is listed FIRST so its overrides take precedence over code/.
# Those overrides are DIAGNOSTICS_SIZE.h, packages.conf, PTRACERS_SIZE.h and
# RADTRANS_SIZE.h (plus the darwin sources). OBCS_OPTIONS.h was listed here
# too until 2026-10-02 and is NOT in code_darwin -- it lives in code/, which
# `readlink build/OBCS_OPTIONS.h` confirms. Corrected because the wrong list
# sends you to edit a file that does not exist and conclude the flag "did not
# take". Same ordering fiji and kerguelen use.
"$DARWIN3/tools/genmake2" -rootdir "$DARWIN3" \
  -of "$DARWIN3/tools/build_options/linux_amd64_ifort+mpi_ice_nas" \
  -mpi -mo "$P/code_drag10 $P/code_swfix $P/code_capload $P/code_darwin $P/code" || exit 1

# --- patch 1: mcmodel/no-relax ---
sed -i '/^LINK = /{/-mcmodel=medium/!s/$/ -mcmodel=medium -Wl,--no-relax/}' Makefile
sed -i '/^FFLAGS = /{/-mcmodel=medium/!s/$/ -mcmodel=medium/}' Makefile
sed -i '/^F90FLAGS = /{/-mcmodel=medium/!s/$/ -mcmodel=medium/}' Makefile

# --- patch 2: strip Intel vendor-gated auto-dispatch ---
sed -i 's/ -axCORE-AVX2 -xSSE4\.2//' Makefile

echo "=== patched Makefile flags ==="
grep -n "^FOPTIM\|^F90OPTIM\|^FFLAGS\|^F90FLAGS\|^LINK" Makefile
echo "=== assert -ax is gone (should print nothing) ==="
grep -n "axCORE-AVX2" Makefile && echo "WARNING: -ax flag survived the sed!"

echo "=== assert radtrans and obcs actually got configured in ==="
grep -cE "ALLOW_RADTRANS" *.h 2>/dev/null | grep -v ":0" | head -3
ls -la RADTRANS_SIZE.h PTRACERS_SIZE.h 2>/dev/null

make depend || exit 1
make -j 16 || exit 1

echo "=== assert iceplume, shelfice, side drag were compiled ==="
ls -la iceplume_calc.o shelfice_thermodynamics.o seaice_sidedrag_stress.o seaice_jfnk.o radtrans_calc.o || echo "WARNING: an expected object is missing"
grep -c RT_iceTransmit RADTRANS_PARAMS.h
echo "=== assert capload overrides compiled ==="
readlink -f seaice_growth.F | grep -q code_swfix || { echo FATAL: seaice_growth.F not from code_swfix; exit 1; }
grep -q "heffTooHeavy = 6. _d 0" seaice_growth.F || { echo FATAL: cap value; exit 1; }
readlink -f SEAICE_OPTIONS.h | grep -q code_capload || { echo FATAL: SEAICE_OPTIONS.h; exit 1; }
grep -q "^#define SEAICE_CAP_ICELOAD" SEAICE_OPTIONS.h || { echo FATAL: CPP; exit 1; }
echo "=== assert swfix overrides compiled ==="
for f in apply_forcing.F seaice_growth.F; do readlink -f $f | grep -q code_swfix || { echo FATAL: $f not from code_swfix; exit 1; }; grep -q "IF ( useGCHEM ) THEN" $f || { echo FATAL: guard missing in $f; exit 1; }; done
echo "BUILD_DONE"
ls -la mitgcmuv
echo "=== static size (bss matters: largest of the three regions) ==="
size mitgcmuv
echo "=== assert drag10 overrides compiled ==="
for f in seaice_lsr.F seaice_oceandrag_coeffs.F seaice_ocean_stress.F seaice_dynsolver.F seaice_ocnvel_avg.F SEAICE_OCNVEL.h; do readlink -f $f | grep -q code_drag10 || { echo FATAL: $f not from code_drag10; exit 1; }; done
ls -la seaice_ocnvel_avg.o mitgcmuv && echo DRAG10_BUILD_OK
