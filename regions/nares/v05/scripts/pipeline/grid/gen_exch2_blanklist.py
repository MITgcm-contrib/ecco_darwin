#!/usr/bin/env python3
"""Write data.exch2 (single facet 1120x360, TX x TY tiles, default 40x40) for the Nares regional run.
A tile is active if it holds any wet cell: bathy < 0 and shelficeTopo > bathy.
Tile ids are x-fastest, 1-based: tId = (ty-1)*28 + tx (pkg/exch2/w2_set_map_tiles.F).
Usage: python3 gen_exch2_blanklist.py <grid dir> <out data.exch2> [TX TY]   (2026-11-16: optional tile size for the scaling test)"""
import sys, numpy as np
g, out = sys.argv[1], sys.argv[2]
NX, NY = 1120, 360
TX, TY = (int(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) > 4 else (40, 40)
assert NX % TX == 0 and NY % TY == 0
b = np.fromfile(f'{g}/Nares_bathymetry.bin', '>f8').reshape(NY, NX)
s = np.fromfile(f'{g}/Nares_shelficeTopo.bin', '>f8').reshape(NY, NX)
wet = (b < 0) & (s > b)
act = wet.reshape(NY//TY, TY, NX//TX, TX).any(axis=(1, 3))
ids = np.arange(1, act.size + 1).reshape(act.shape)
blank = ids[~act]
assert len(set(blank)) == blank.size and blank.min() >= 1 and blank.max() <= act.size
rows = [', '.join(f'{v:4d}' for v in blank[k:k+10]) for k in range(0, blank.size, 10)]
with open(out, 'w') as f:
    f.write(f"""# data.exch2 -- Nares Strait 1-km rotated grid (one facet).
#
# Generated by python/nares_strait/gen_exch2_blanklist.py from
# Nares_bathymetry.bin + Nares_shelficeTopo.bin. DO NOT hand-edit the
# blankList: rerun the script whenever the bathymetry or shelf changes.
#
# Geometry: one facet, {NX} x {NY}, split {NX//TX} x {NY//TY} into {TX} x {TY} tiles = {act.size}.
# {blank.size} tiles hold no wet cell and are blanked, leaving {act.sum()} ACTIVE tiles,
# which SIZE.h nPx*nPy must equal. Tile ids are X-fastest, 1-based:
# tId = (ty-1)*{NX//TX} + tx.
 &W2_EXCH2_PARM01
 W2_printMsg = 0,
 dimsFacets = {NX}, {NY},
 blankList=
""" + ',\n'.join('    ' + r for r in rows) + ',\n &\n')
print(f'{act.sum()} active, {blank.size} blank -> {out}')
